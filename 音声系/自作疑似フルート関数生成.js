(() => {
    // --- 周波数設定 ---
    var f =880; 
    // ----------------
    
    var w = t * f * 2 * PI;
    var y = 0;
    
    // フルート風の位相設定（変更なし）
    var phases = [90, 30, 120, 80, 90];

    // ★重要: 減衰係数のベースを 2.8 に設定
    // 周波数が高いほど、さらに係数が大きくなる（倍音が減る）計算
    // 例: 440Hz -> 3.0, 880Hz -> 6.0, 220Hz -> 1.5
    var decay_base = 2.8 * (f / 440.0);
    
    // 低音で係数が小さくなりすぎてノイズになるのを防ぐリミッター(1.1以上にする)
    if (decay_base < 1.1) decay_base = 1.1;

    // 倍音加算ループ
    for (var n = 1; n <= 12; n++) {
        // 係数 decay_base を使って振幅を計算
        // n=1: 1
        // n=2: 1 / 3
        // n=3: 1 / 9 ...
        var amp = 1 / pow(decay_base, n - 1);
        
        // 位相計算
        var deg = (n - 1 < phases.length) ? phases[n - 1] : 0;
        var rad = deg * PI / 180;
        
        y += amp * sin(n * w + rad);
    }
    
    // 振幅が小さいのでゲインを少し上げて出力
    return y * 0.8;
})()
